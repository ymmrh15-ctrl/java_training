package chap_1;

public class P60Main_3 {
	public static void main(String[] args) {
		//真偽値を定義して表示
		boolean singi = true;
		System.out.println(singi);
		//文字を1つを定義して表示
		char mozi = '駆';
		System.out.println(mozi);
		//小数を定義して表示
		double kazu = 3.14;
		System.out.println(kazu);
		//大きい整数を定義して表示
		long suzi = 314159265853979L;
		System.out.println(suzi);
		//文字列を定義して表示
		String bun = "ミナトの攻撃！敵に15ポイントのダメージを与えた。";
		System.out.println(bun);
	}
} 